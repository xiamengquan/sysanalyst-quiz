DEAD = re.compile(r"^[-*]\s*\*\*(本章练习热力|题库考点标签|练题入口)\*\*.*$", re.M)

def main():
    ok, skipped, missing = [], [], []
    for kid, trio in TRIO.items():
        f = ROOT / "content/kb/points" / f"{kid}.md"
        if not f.exists():
            missing.append(kid); continue
        t = f.read_text(encoding="utf-8")
        t = DEAD.sub("", t)
        if TRIO_HEAD in t:
            skipped.append(kid); f.write_text(t, encoding="utf-8"); continue
        if "## 相关考点" not in t:
            skipped.append(f"{kid}(no-anchor)"); continue
        how, ans, trap = trio
        block = (f"\n{TRIO_HEAD}\n\n"
                 f"- **怎么考**：{how}\n"
                 f"- **怎么答**：{ans}\n"
                 f"- **易错与扣分**：{trap}\n\n")
        t = t.replace("## 相关考点", block + "## 相关考点", 1)
        t = re.sub(r"\n{3,}", "\n\n", t)
        f.write_text(t, encoding="utf-8")
        ok.append(kid)
    print(f"trio done: {len(ok)}, skipped: {skipped}, missing: {missing}")

if __name__ == "__main__":
    main()