def build_q(stage, point, diff, stem, opts, ans, exp, no: int) -> dict:
    qid = mid(stage, point, stem[:48], ans)
    return {
        "no": no,
        "id": qid,
        "chapter": 11,
        "point": point,
        "stem": stem,
        "options": opts,
        "answer": ans,
        "explain": exp,
        "difficulty": diff,
        "source": "结构化与OO分析体系化问答",
        "intensity": "boost" if stage in {"L2", "L4"} else "stable",
        "style_track": "short",
        "learn_path": LEARN_PATH,
        "learn_stage": stage,
        "audience": ["frontend"],
    }


def main():
    rows = [json.loads(l) for l in PRACTICE.read_text(encoding="utf-8").splitlines() if l.strip()]
    existing_ids = {r["id"] for r in rows}
    # remove previous sao batch if re-run
    rows = [r for r in rows if not (r.get("learn_path") == LEARN_PATH and str(r.get("source", "")).startswith("结构化与OO"))]
    existing_ids = {r["id"] for r in rows}
    max_no = max((r["no"] for r in rows), default=0)
    new_rows = []
