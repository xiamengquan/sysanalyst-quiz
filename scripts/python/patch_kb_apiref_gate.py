def patch(fname: str, subs: list[tuple[str, str]]) -> None:
    p = POINTS / fname
    t = p.read_text(encoding="utf-8")
    for old, new in subs:
        if old not in t:
            STATS.setdefault("未命中", []).append(f"{fname}: {old[:40]}")
            continue
        t = t.replace(old, new, 1)
        STATS["替换"] = STATS["替换"] + 1
    p.write_text(t, encoding="utf-8")


