def strip_html(s: str) -> str:
    if not s:
        return ""
    s = s.replace("<br/>", "\n").replace("<br>", "\n").replace("</p>", "\n").replace("<p>", "")
    s = re.sub(r"<[^>]+>", "", s)
    s = s.replace("&nbsp;", " ").replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


