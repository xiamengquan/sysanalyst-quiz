def write_mcq(questions):
    MCQ_DIR.mkdir(parents=True, exist_ok=True)
    by_ch: dict[int, list] = {}
    for q in questions:
        by_ch.setdefault(q["chapter"], []).append(q)

    all_ans = []
    index_lines = [
        "# 综合知识练习题库（约2000题）",
        "",
        "> 依据系统分析师教程/大纲知识点**自编练习题**，非历年真题原题照搬。答案见各章文末与 `综合知识-答案汇总.md`。",
        "",
        f"**题目总数：{len(questions)}**",
        "",
        "| 章 | 主题 | 题量 | 文件 |",
        "|----|------|------|------|",
    ]

    for ch in sorted(by_ch):
        qs = by_ch[ch]
        name = CHAPTER_NAMES.get(ch, f"第{ch}章")
        fname = f"第{ch:02d}章-{name}.md"
        lines = [f"# 综合知识 · 第{ch}章 {name}", "", f"共 {len(qs)} 题。先做题再对答案。", "", "---", ""]
        for q in qs:
            lines.append(f"### {q['no']}. {q['stem']}")
            lines.append("")
            for k in "ABCD":
                lines.append(f"- {k}. {q['options'][k]}")
            lines.append("")
            lines.append(f"<!-- ANS {q['answer']} | {q['point']} -->")
            lines.append("")
            all_ans.append((q["no"], q["id"], ch, q["answer"], q["point"], q["explain"]))

        lines.append("---")
        lines.append("")
        lines.append("## 本章答案速查")
        lines.append("")
        # compact answers
        chunk = []
        for q in qs:
            chunk.append(f"{q['no']}-{q['answer']}")
        lines.append(" ".join(chunk))
        lines.append("")
        (MCQ_DIR / fname).write_text("\n".join(lines), encoding="utf-8")
        index_lines.append(f"| {ch} | {name} | {len(qs)} | [{fname}](./{fname}) |")

    (MCQ_DIR / "00-目录.md").write_text("\n".join(index_lines) + "\n", encoding="utf-8")

    ans_lines = ["# 综合知识 · 答案汇总", "", "| 题号 | 章 | 答案 | 考点 |", "|------|----|------|------|"]
    for no, qid, ch, ans, point, expl in all_ans:
        ans_lines.append(f"| {no} | {ch} | **{ans}** | {point} |")
    (MCQ_DIR / "综合知识-答案汇总.md").write_text("\n".join(ans_lines) + "\n", encoding="utf-8")

    # JSONL for tooling
    with (MCQ_DIR / "all.jsonl").open("w", encoding="utf-8") as f:
        for q in questions:
            f.write(json.dumps(q, ensure_ascii=False) + "\n")


