def qid(*parts):
    return hashlib.md5("||".join(map(str, parts)).encode()).hexdigest()[:10]

def pack(ch, point, stem, correct, wrongs, explain, difficulty="deep"):
    wrongs = list(wrongs)[:3]
    while len(wrongs) < 3:
        wrongs.append("以上说法均不正确")
    opts = [correct] + wrongs
    rnd = random.Random(qid(ch, point, stem))
    rnd.shuffle(opts)
    ans = "ABCD"[opts.index(correct)]
    return {
        "chapter": ch,
        "point": point,
        "stem": stem,
        "options": {"A": opts[0], "B": opts[1], "C": opts[2], "D": opts[3]},
        "answer": ans,
        "explain": explain,
        "difficulty": difficulty,
    }

