# Load existing
old = []
for line in (MCQ_DIR / "all.jsonl").read_text(encoding="utf-8").splitlines():
    if line.strip():
        q = json.loads(line)
        q.setdefault("difficulty", "basic")
        old.append(q)

# Dedup deep by stem
existing_stems = {q["stem"] for q in old}
added = []
for q in DEEP:
    if q["stem"] in existing_stems:
        continue
    existing_stems.add(q["stem"])
    added.append(q)

# Renumber all: keep old nos then continue; better rebuild sequential
all_q = old + added
# stable sort: chapter, difficulty(basic first), stem
diff_rank = {"basic": 0, "deep": 1}
all_q.sort(key=lambda x: (x["chapter"], diff_rank.get(x.get("difficulty","basic"),0), x["stem"]))
for i, q in enumerate(all_q, 1):
    q["no"] = i
    q["id"] = f"CK-{q['chapter']:02d}-{qid(q['stem'], q['answer'], i)}"

# Write jsonl
with (MCQ_DIR / "all.jsonl").open("w", encoding="utf-8") as f:
    for q in all_q:
        f.write(json.dumps(q, ensure_ascii=False) + "\n")

# Rewrite chapter md files
by_ch = defaultdict(list)
for q in all_q:
    by_ch[q["chapter"]].append(q)

index_lines = [
    "# 综合知识练习题库",
    "",
    f"> 自编练习题。含基础题与深度题。总数：**{len(all_q)}**（深度题约 {len(added)} 道新增）。",
    "",
    "| 章 | 主题 | 题量 | 文件 |",
    "|----|------|------|------|",
]
ans_lines = ["# 综合知识 · 答案汇总", "", "| 题号 | 章 | 难度 | 答案 | 考点 |", "|------|----|------|------|------|"]

for ch in sorted(by_ch):
    qs = by_ch[ch]
    name = CH_NAMES.get(ch, f"第{ch}章")
    fname = f"第{ch:02d}章-{name}.md"
    lines = [f"# 综合知识 · 第{ch}章 {name}", "", f"共 {len(qs)} 题。", "", "---", ""]
    for q in qs:
        diff = q.get("difficulty", "basic")
        tag = "深度" if diff == "deep" else "基础"
        lines.append(f"### {q['no']}. [{tag}] {q['stem']}")
        lines.append("")
        for k in "ABCD":
            lines.append(f"- {k}. {q['options'][k]}")
        lines.append("")
        lines.append(f"<!-- ANS {q['answer']} | {q['point']} | {diff} -->")
        lines.append("")
        ans_lines.append(f"| {q['no']} | {ch} | {tag} | **{q['answer']}** | {q['point']} |")
    lines.append("---\n\n## 本章答案速查\n")
    lines.append(" ".join(f"{q['no']}-{q['answer']}" for q in qs))
    lines.append("")
    (MCQ_DIR / fname).write_text("\n".join(lines), encoding="utf-8")
    index_lines.append(f"| {ch} | {name} | {len(qs)} | [{fname}](./{fname}) |")

(MCQ_DIR / "00-目录.md").write_text("\n".join(index_lines) + "\n", encoding="utf-8")
(MCQ_DIR / "综合知识-答案汇总.md").write_text("\n".join(ans_lines) + "\n", encoding="utf-8")

