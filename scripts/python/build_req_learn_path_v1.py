def build_q(stage, point, diff, stem, opts, ans, exp, no: int) -> dict:
    qid = mid(stage, point, stem[:40], ans)
    return {
        "no": no,
        "id": qid,
        "chapter": 11,
        "point": point,
        "stem": stem,
        "options": opts,
        "answer": ans,
        "explain": exp,
        "difficulty": diff,
        "source": "需求工程体系化问答",
        "intensity": "boost" if stage in {"L2", "L4"} else "stable",
        "style_track": "short",
        "learn_path": "req",
        "learn_stage": stage,
        "audience": ["frontend"],
    }


def tag_existing(rows: list[dict]) -> int:
    n = 0
    for r in rows:
        if r.get("chapter") != 11:
            continue
        if r.get("learn_path") == "req" and r.get("learn_stage"):
            continue
        stage = POINT_STAGE.get(r.get("point") or "", "L2")
        r["learn_path"] = "req"
        r["learn_stage"] = stage
        n += 1
    return n


def write_chapter_md(ch11: list[dict]):
    lines = [f"# 综合知识 · 第11章 软件需求工程", "", f"共 {len(ch11)} 题（含需求工程 L0–L4 体系化问答）。", "", "---", ""]
    for q in ch11:
        st = q.get("learn_stage", "")
        lines.append(f"### {q['no']}. [{q.get('difficulty','')}/{st}] {q['stem']}")
        lines.append("")
        for k in "ABCD":
            lines.append(f"- {k}. {q['options'][k]}")
        lines.append("")
        lines.append(f"<!-- ANS {q['answer']} | {q.get('point','')} | {q.get('difficulty','')} | {st} -->")
        lines.append("")
    CH_MD.write_text("\n".join(lines), encoding="utf-8")


def main():
    rows = [json.loads(l) for l in PRACTICE.read_text(encoding="utf-8").splitlines() if l.strip()]
    tagged = tag_existing(rows)
    existing_ids = {r["id"] for r in rows}
    max_no = max(r["no"] for r in rows)
    new_rows = []
    no = max_no
    for item in RAW:
        no += 1
        q = build_q(*item, no=no)
        if q["id"] in existing_ids:
            # rare hash clash: tweak
            q["id"] = mid(q["id"], str(no))
        existing_ids.add(q["id"])
        new_rows.append(q)
        rows.append(q)

    PRACTICE.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    BATCH.write_text(
        "# 批次说明 · 需求工程体系化问答\n\n"
        f"- 新增 {len(new_rows)} 题写入 `practice/all.jsonl`，打标 `learn_path=req`，`learn_stage=L0…L4`\n"
        f"- 既有第11章题补标 {tagged} 题\n"
        "- 刷题路径：需求工程（L0→L4）\n"
        "- 教程：`content/kb/速查/需求工程-体系化学习路径.md`\n",
        encoding="utf-8",
    )
    ch11 = [r for r in rows if r.get("chapter") == 11]
    ch11.sort(key=lambda r: (r.get("learn_stage") or "L9", r["no"]))
    write_chapter_md(ch11)
    stages = Counter(r.get("learn_stage") for r in ch11)
    print({"ch11_total": len(ch11), "new": len(new_rows), "tagged_old": tagged, "stages": dict(stages)})

if __name__ == "__main__":
    main()
