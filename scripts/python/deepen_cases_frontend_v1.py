def parse_title(text: str):
    m = re.match(r"#\s*案例(\d+)\s*·\s*(.+?)\s*·\s*(.+)$", text.splitlines()[0].strip())
    return int(m.group(1)), m.group(2).strip(), m.group(3).strip()

def deepen_stem_p0(domain: str, typ: str, stem: str) -> str:
    """在原有题干上叠加更深约束（不丢王工/李工）。"""
    extras = {
        "Web": (
            "补充约束：前端多端（Web/小程序）共用同一套计价与库存视图；"
            "大促出现缓存击穿与恶意穿透风险；不允许长时间停机；需可灰度回滚。"
        ),
        "移动": (
            "补充约束：iOS 审核周期长，热更新能力受限；弱网下须防重复提交；"
            "禁止双端维护两套优惠券核销规则；会员等级口径必须与中台一致。"
        ),
        "微服务": (
            "补充约束：下单链路跨订单/库存/支付服务；允许非核心降级；"
            "要求契约测试与熔断限流；发布窗口短，禁止多服务无序同时变更。"
        ),
        "集成": (
            "补充约束：ERP 不可改核心代码；接口须可审计可重试；"
            "新渠道 3 个月内上线；主数据（客户/商品）编码冲突已发生过事故。"
        ),
        "需求": (
            "补充约束：干系人多且冲突；领导只给模糊目标；"
            "须在固定预算与工期内交付首期；接口边界（如 SAP）未书面确认。"
        ),
    }
    if domain not in extras:
        return stem
    if "补充约束" in stem:
        return stem
    return stem.rstrip() + "\n" + extras[domain]

def deepen_rubrics(domain: str, typ: str, track: str, stop_loss: bool) -> tuple[str, str, str, str]:
    if stop_loss:
        r1 = "止损答法：先写架构分层/对比表骨架；填空优先教材标准词（调度、优先级反转、看门狗、感知-决策-执行、MQTT 等）。"
        r2 = "写清 1 句权衡：虽××更理想，但题干约束下应××；至少回扣 2 个题干词。"
        r3 = "给出可观测门禁：超时/丢包/急停优先级/审计日志 任选 ≥3 个指标。"
        hint = f"{domain} · 止损域：只求踩分，不深挖工程细节"
        return r1, r2, r3, hint
    if domain == "需求":
        r1 = "若问三类需求：分别定义业务/用户/系统需求并各举题干式例子；若问获取方法：按目标匹配访谈/JRP/问卷/文档/观察。"
        r2 = "对比须用维度：需求广度、深度、信息集成度、用户参与度；禁止只写「更好」。"
        r3 = "限字简答先结论后要点；每点回扣题干干系人或工期/预算约束。"
        hint = "需求 · 必答底座：方法对比 + 限字"
        return r1, r2, r3, hint
    if domain == "Web":
        r1 = "对比/分层须点名：接入层（CDN/网关限流）、BFF、缓存（击穿/穿透对策）、业务、ERP 适配；职责不重叠。"
        r2 = "措施具体：布隆过滤防穿透、互斥/逻辑过期防击穿、Write-Through/Behind 取舍、灰度回滚；每条对应题干痛点。"
        r3 = "风险：最终一致→对账幂等；缓存雪崩→限流降级；双端规则分裂→中台统一；给监控指标。"
        hint = "Web · P0 加深：大促缓存与多端统一"
        return r1, r2, r3, hint
    if domain == "移动":
        r1 = "对比原生/混合/小程序或双端规则：审核、弱网、包体积、热更新、体验差异层。"
        r2 = "统一规则沉到 BFF/中台；客户端只保留展示差异；幂等键防弱网重提。"
        r3 = "指标：重复下单率、核销不一致率、崩溃率、弱网成功率。"
        hint = "移动 · P0 加深：多端规则与审核约束"
        return r1, r2, r3, hint
    if domain in ("微服务", "集成"):
        r1 = "点名网关/注册发现/熔断舱壁/消息总线或 ESB/防腐层；对照题干遗留与工期。"
        r2 = "关键路径同步、非关键异步；契约测试；库存乐观锁/预扣；ERP 适配器不可侵入核心。"
        r3 = "风险：分布式事务、发布雪崩、主数据不一致；应对：Saga/对账、灰度、主数据服务。"
        hint = f"{domain} · P0 加深：集成与韧性"
        return r1, r2, r3, hint
    # P1 generic deepen
    r1 = "分层/对比紧扣题干质量属性；构件名前后一致。"
    r2 = "措施可落地并点明作用点；至少 3 条对应痛点。"
    r3 = "风险+门禁/监控；指标可量化。"
    hint = f"{domain} · {track} 保底交叉"
    return r1, r2, r3, hint

def rewrite_existing():
    n = 0
    for fp in sorted(CASE_DIR.glob("案例*.md"), key=lambda p: int(re.search(r"\d+", p.stem).group())):
        text = fp.read_text(encoding="utf-8")
        no, domain, typ = parse_title(text)
        track = TRACK_MAP.get(domain, "P1")
        stop_loss = domain in ("嵌入式", "CPS")
        stem_m = re.search(r"##\s*题干\s*\n(.*?)(?=\n##\s)", text, re.S)
        if not stem_m:
            continue
        stem = stem_m.group(1).strip()
        if track == "P0":
            stem = deepen_stem_p0(domain, typ, stem)
        r1, r2, r3, hint = deepen_rubrics(domain, typ, track, stop_loss)
        # keep questions block
        q_m = re.search(r"##\s*问题\s*\n(.*?)(?=\n##\s)", text, re.S)
        qblock = q_m.group(1).strip() if q_m else ""
        meta = f"track: {track}" + (" · stop_loss" if stop_loss else "") + " · depth: deep"
        new = f"""# 案例{no:03d} · {domain} · {typ}

> {meta}

## 题干

{stem}

## 问题

{qblock}

## 参考作答要点（非唯一答案）

**问题1要点：** {r1}

**问题2要点：** {r2}

**问题3要点：** {r3}

**领域提示：** {hint}；答题回扣题干约束。
"""
        fp.write_text(new, encoding="utf-8")
        n += 1
    return n

