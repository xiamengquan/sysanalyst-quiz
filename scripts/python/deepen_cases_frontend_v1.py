def build_catalog():
    rows = []
    for fp in sorted(CASE_DIR.glob("案例*.md"), key=lambda p: int(re.search(r"\d+", p.stem).group())):
        no, domain, typ = parse_title(fp.read_text(encoding="utf-8"))
        track = TRACK_MAP.get(domain, "P1")
        rows.append((no, domain, typ, track))
    lines = [
        "# 案例分析练习题库",
        "",
        "> 依据《复习重点报告-前端工程师-案例分析五选三-v1.0》加深加重。",
        "> 重建：`npm run sync:data` 或 `python3 scripts/python/build_cases_jsonl.py`",
        "",
        "| 编号 | 领域 | 题型 | 路径 | 文件 |",
        "|------|------|------|------|------|",
    ]
    for no, domain, typ, track in rows:
        lines.append(f"| {no:03d} | {domain} | {typ} | {track} | [案例{no:03d}.md](./案例{no:03d}.md) |")
    lines.append("")
    lines.append(f"**合计** {len(rows)} 套 · P0={sum(1 for r in rows if r[3]=='P0')} · P1={sum(1 for r in rows if r[3]=='P1')} · P2={sum(1 for r in rows if r[3]=='P2')}")
    (CASE_DIR / "00-目录.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows

def write_packs(rows):
    PACK_DIR.mkdir(parents=True, exist_ok=True)
    by_dom = {}
    for no, domain, typ, track in rows:
        by_dom.setdefault(domain, []).append(no)

    def pick(domain, i=0):
        xs = by_dom.get(domain) or []
        return xs[i % len(xs)] if xs else None

    packs = []
    # 5 packs: each 1 需求(必答) + 4 from Web/移动/微服务/集成/大数据/嵌入式
    templates = [
        ("pack-01", [pick("需求", 0), pick("Web", 0), pick("移动", 0), pick("微服务", 0), pick("嵌入式", 0)]),
        ("pack-02", [pick("需求", 1), pick("Web", 1), pick("集成", 0), pick("大数据", 0), pick("CPS", 0)]),
        ("pack-03", [pick("需求", 2), pick("移动", 1), pick("微服务", 1), pick("安全", 0), pick("嵌入式", 1)]),
        ("pack-04", [pick("需求", 3), pick("Web", 2), pick("集成", 1), pick("测试", 0), pick("CPS", 1)]),
        ("pack-05", [pick("需求", 4), pick("微服务", 2), pick("移动", 2), pick("运维", 0), pick("大数据", 1)]),
    ]
    for pid, nos in templates:
        nos = [n for n in nos if n]
        packs.append({
            "id": pid,
            "title": f"五选三模拟 · {pid}",
            "rule": "试题一必答；试题二～五选答两题",
            "mandatory": nos[0] if nos else None,
            "elective": nos[1:],
            "select_hint": "60秒扫标题：优先 Web/移动/微服务/集成；嵌入式/CPS 非硬实时才选",
            "cases": [f"CA-{n:03d}" for n in nos],
        })
    (PACK_DIR / "wuxuan-san.json").write_text(
        json.dumps({"version": "v1", "packs": packs}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (OUT_DATA / "case-packs.json").write_text(
        json.dumps({"version": "v1", "packs": packs}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return packs

