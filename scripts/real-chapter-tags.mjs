/** 英语阅读题（真题尾部 5 题，长英文题干）——无独立章号，归 0 杂项 */
export function looksLikeEnglishQuestion(text) {
  const letters = text.replace(/[^A-Za-z]/g, "").length;
  return letters / Math.max(1, text.length) > 0.6;
}

/**
 * 打标：返回所属章节号。
 * @param q 真题行（stem/opts/exp）
 */
export function tagRealChapter(q) {
  const text = [q.stem || "", Object.values(q.opts || {}).join(" "), q.exp || ""].join("\n");
  if (looksLikeEnglishQuestion(q.stem || "")) return 0;
  let best = { ch: 99, hits: 0 };
  for (const { ch, kw } of CHAPTER_KEYWORDS) {
    let hits = 0;
    for (const k of kw) {
      if (text.toLowerCase().includes(k.toLowerCase())) hits++;
    }
    if (hits > best.hits) best = { ch, hits };
  }
  return best.hits > 0 ? best.ch : 99;
}
